# 数
# 一 整数 int
# 1. 整数的定义
print(10)
print(-10)
print(0)
# 四则运算
print(10 + 20)
print(10 - 20)
print(10 * 20)
print(10 / 20)
# 整数的取整运算
print(10 // 20)
# 整数的指数运算
print(10 ** 20)
# 整数的取余运算
print(10 % 20)

# 二 浮点数 float
print(10.0)
print(-10.0)
print(0.0)
# 四则运算
print(10.0 + 20.0)
print(10.0 - 20.0)
print(10.0 * 20.0)
print(10.0 / 20.0)
# 浮点数的取整运算
print(10.0 // 20.0)
# 浮点数的指数运算
print(10.0 ** 20.0)
# 浮点数的取余运算
print(10.0 % 20.0)

# 三 浮点数与整数运算
print(3.14 + 10)
print(10 / 3)
# 四 科学计数法
print(10.2e3)
print(14_000_000_000)
# 五 数字常量
PI = 3.14
print(PI)
# 六 数字的类型转换
print(int(3.99))
print(float(10))
# 七 布尔值 bool
print(True)
print(False)
print(int(True))
print(int(False))
print(float(True))
print(float(False))


